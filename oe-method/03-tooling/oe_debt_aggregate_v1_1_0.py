#!/usr/bin/env python3
"""oe_debt_aggregate_v1_0_0 - build the governance debt aggregate from the packages' own registers, and refuse to widen it.

THE ARRANGEMENT (the owner's ruling of 2026-10-07). Each package carries its own structure-debt register, in its own
package, and clears its own lines in its own release -- which is what BP-D54 always said and what a single central file
made impossible. The governance package keeps the rules and this AGGREGATE: the ecosystem-wide view, and the ceiling
baseline the checker's guards compare a local register against.

WHY THE AGGREGATE IS GENERATED AND STILL TRUSTWORTHY. If regenerating simply copied whatever each package now says, a
session could raise its own ceiling and the next aggregate would bless it -- the ratchet would certify itself, which is
the one guarantee the single central file bought. So this generator is a ratchet too:

  shrinks        a lower count, or a line a package has removed, is taken as given: debt may always shrink
  grows          a higher count, a line no previous aggregate carried, or a status raised to `exception` is REFUSED:
                 the previous ceiling is kept, the attempt is reported, and the run fails unless the line carries a
                 recorded ruling (a note containing `ruling:`), which only the owner's decision puts there
  not adopted    a package with no register of its own keeps its lines from the previous aggregate, unchanged, so
                 adoption is incremental and nothing is blocked while packages adopt
  elsewhere      a package that is not in this tree at all keeps its lines from the previous aggregate: its register
                 lives where the package lives and cannot be read from here (L-137 -- absence is not clearance)

  oe_debt_aggregate_v1_1_0.py <root> --previous <aggregate.tsv> [--out <aggregate.tsv>] [--verify]

--verify writes nothing and is the form CI runs. It FAILS when a package's own register raises debt (a refused line, a new line,
anything that is not a shrink). When the only difference is that packages cleared or shrank lines (good news the aggregate has
not caught up with), it prints a warning, names the lines and exits 0: a package's legitimate shrink must not turn another
release red (L-152). The aggregate is then regenerated by OEE in its next release. Without --out it prints the aggregate it would write.
"""
import glob, os, re, sys


def read(path):
    reg = {}
    for ln in open(path, encoding="utf-8"):
        ln = ln.rstrip("\n")
        if not ln or ln.startswith("#"):
            continue
        parts = ln.split("\t")
        if len(parts) < 3:
            raise ValueError("register line needs rule, path, status: " + ln[:80])
        reg[(parts[0], parts[1])] = parts[2:]
    return reg


def count_of(fields):
    m = re.search(r"(?:files|missing)=(\d+)", " ".join(fields))
    return int(m.group(1)) if m else None


def local_of(root, pkg):
    d = os.path.join(root, pkg, "04-documentation", "structure-debt")
    c = glob.glob(os.path.join(d, "STRUCTURE_DEBT_REGISTER_v*.tsv"))
    if not c:
        return None
    return sorted(c, key=lambda p: [int(x) for x in re.findall(r"\d+", os.path.basename(p))])[-1]


def main(argv):
    if "--previous" not in argv or len(argv) < 2:
        print(__doc__); return 2
    root = argv[1]
    prev_path = argv[argv.index("--previous") + 1]
    out = argv[argv.index("--out") + 1] if "--out" in argv else None
    verify = "--verify" in argv
    prev = read(prev_path)
    prev_pkgs = sorted({k[1].split(os.sep)[0] for k in prev})
    here = {d for d in os.listdir(root) if os.path.isdir(os.path.join(root, d)) and not d.startswith(".")}

    adopted, kept_no_register, kept_absent = {}, [], []
    for p in prev_pkgs:
        if p not in here:
            kept_absent.append(p); continue
        lp = local_of(root, p)
        if lp is None:
            kept_no_register.append(p); continue
        if os.path.exists(prev_path) and os.path.samefile(lp, prev_path):
            kept_no_register.append(p); continue       # that file IS the aggregate, not a package's own register
        adopted[p] = (lp, read(lp))

    new, refused, shrunk, dropped = {}, [], [], []
    for k, v in prev.items():
        p = k[1].split(os.sep)[0]
        if p not in adopted:
            new[k] = v                                  # not adopted, or not in this tree: unchanged
    for p, (lp, lreg) in sorted(adopted.items()):
        for k, v in prev.items():
            if k[1].split(os.sep)[0] != p:
                continue
            if k not in lreg:
                dropped.append((k, p)); continue        # the package cleared it: debt shrank
            lv = lreg[k]
            cp, cl = count_of(v[1:]), count_of(lv[1:])
            ruled = any("ruling:" in f for f in lv[1:])
            if lv[0] == "exception" and v[0] != "exception" and not ruled:
                refused.append((k, p, f"status raised to exception (aggregate has {v[0]})")); new[k] = v; continue
            if cp is not None and cl is not None and cl > cp and not ruled:
                refused.append((k, p, f"count raised from {cp} to {cl}")); new[k] = v; continue
            if cp is not None and cl is not None and cl < cp:
                shrunk.append((k, p, f"{cp} -> {cl}"))
            new[k] = lv
        for k, v in lreg.items():
            if k[1].split(os.sep)[0] != p:
                refused.append((k, p, "a package's own register carries another package's line")); continue
            if k not in prev and not any("ruling:" in f for f in v[1:]):
                refused.append((k, p, "line is not in the previous aggregate: new debt needs a ruling")); continue
            if k not in prev:
                new[k] = v

    hdr = ("# STRUCTURE DEBT AGGREGATE -- generated by oe_debt_aggregate_v1_1_0.py from each package's own register.\n"
           "# Do not hand-edit a line for a package that carries its own register: edit it there, in that package's release.\n"
           "# This file is the CEILING BASELINE. A count may fall from a package's own register; it rises only here, and only\n"
           "# with the owner's ruling recorded in the line's note as `ruling: ...`.\n"
           "# Rules: N1 name, N2 patch name, V1 versions side by side, R1 mixed roles, H1 more than one ontology header,\n"
           "# U1 more than one active file of a role in a package, A1 the same for the archive, M1 membership (opt-in).\n"
           "# status: debt | pending-ruling | exception (an exception names the owner's ruling)\n")
    body = "".join("\t".join([k[0], k[1]] + list(v)) + "\n" for k, v in sorted(new.items(), key=lambda kv: (kv[0][1], kv[0][0])))
    text = hdr + body

    print(f"packages: {len(adopted)} with their own register, {len(kept_no_register)} not adopted yet, "
          f"{len(kept_absent)} not in this tree")
    print(f"lines: {len(prev)} -> {len(new)}; {len(dropped)} cleared by their package, {len(shrunk)} shrunk, {len(refused)} refused")
    for k, p, why in refused[:20]:
        print(f"  REFUSED {k[0]} {k[1]} -- {why}; the previous ceiling is kept")
    for k, p, why in shrunk[:10]:
        print(f"  shrunk  {k[0]} {k[1]} -- {why}")
    for k, p in dropped[:10]:
        print(f"  cleared {k[0]} {k[1]} -- {p} removed it from its own register")
    if verify:
        # The rows are the aggregate's content; the header is prose and may be improved without the file being stale.
        rows = lambda t: sorted(l for l in t.splitlines() if l and not l.startswith("#"))
        same = rows(text) == rows(open(prev_path, encoding="utf-8").read())
        shrunk_keys = {k for k, p, why in shrunk}
        only_shrink = (not same) and not refused and all(
            (k not in new and k in prev) or (k in new and k in prev and k in shrunk_keys)
            for k in set(new) | set(prev) if new.get(k) != prev.get(k))
        if same:
            print("verify: the aggregate is current")
        elif only_shrink:
            print(f"verify: WARNING -- the aggregate is behind its packages ({len(dropped)} cleared, {len(shrunk)} shrunk); "
                  "debt only fell, so this is not a failure. Regenerate it in the next oe-pack release.")
            print(f"::warning title=Debt aggregate behind::{len(dropped)} cleared and {len(shrunk)} shrunk lines; regenerate in the next oe-pack release")
        else:
            print("verify: the aggregate is NOT current -- regenerate it (the difference is not only a shrink)")
        return 1 if (refused or not (same or only_shrink)) else 0
    if out:
        open(out, "w", encoding="utf-8").write(text)
        print("written: " + out)
    else:
        sys.stdout.write(text)
    return 1 if refused else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
