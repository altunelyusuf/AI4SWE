#!/usr/bin/env python3
"""
verify_manifest_v1_1_0.py — a manifest self-check that catches stowaways, not only tampering.

Real finding this fixes (handover: fizyovibe-admin -> OE, 2026-09-13, Finding 2, verified
directly before this tool was built, reproduced independently on both the shared bash idiom
`sha256sum -c` and this repo's own inline-Python equivalent, used dozens of times this session):
a manifest self-check that only verifies the files a manifest LISTS is silent about a file that
exists on disk and is not listed. A tampered or missing listed file is caught; an unlisted
stowaway is not, and every prior inline check this session ran had that exact blind spot.

This tool checks both directions:
  - every listed file exists and hashes correctly (the check that already existed), and
  - every real file under the tree (excluding the manifest itself and paths the caller excludes)
    is actually listed in the manifest (the check that did not exist before this tool).

v1.1.0: a real, self-implicating finding (handover: agentic-sdlc -> OE, 2026-09-21), reproduced
directly before fixing: v1.0.0's bidirectional check had no exclusion for a file that is
structurally, legitimately unable to appear in the manifest it is checked against -- a file
generated by the publish process AFTER the manifest step (PUBLISH_RECORD.ttl), or a file that
carries the manifest's own digest, which cannot itself be inside the set the digest covers (the
same principle the manifest file's own self-exclusion already rests on; see
backlog:manifestDigestCarriedBy's own comment, "the root of a hash-covered set lives outside the
set"). Rather than a hardcoded filename list, which only covers this session's own two named
cases, a manifest may declare its own exemptions with a `# EXEMPT: <path>` comment line -- the
exemption travels with the package, visible in the manifest itself, matching the governing
SHACL shape's own language ("the carrier is declared exempt in the manifest").

Usage:
    python3 verify_manifest_v1_1_0.py <manifest_path> [--root <dir>] [--exclude <glob> ...]

A manifest may declare additional exemptions with comment lines: `# EXEMPT: PUBLISH_RECORD.ttl`.

Exit 0 only if every listed file verifies AND no stowaway exists. Reports counts, not just a
verdict (BP-D4): "N/N listed files verify" and "M stowaway(s) found" are both stated, never
just "clean".
"""
import sys
import os
import re
import hashlib
import argparse
import fnmatch


def parse_manifest(manifest_path):
    """Return ({relative_path: sha256_hex}, set-of-declared-exemptions) for a manifest.
    A declared exemption is a comment line of the form '# EXEMPT: <path>', naming a file that
    structurally cannot be listed (generated after the manifest step, or itself carries the
    manifest's own digest -- see backlog:manifestDigestCarriedBy's own comment: 'the root of a
    hash-covered set lives outside the set'). Declaring it in the manifest, rather than only at
    the caller's --exclude flag, keeps the exemption visible and travels with the package."""
    entries = {}
    exemptions = set()
    with open(manifest_path) as f:
        for line in f:
            line = line.rstrip("\n")
            if not line:
                continue
            if line.startswith("#"):
                m = re.match(r'^#\s*EXEMPT:\s*(\S+)', line)
                if m:
                    exemptions.add(m.group(1))
                continue
            m = re.match(r'^([0-9a-f]{64})\s+(.+?)\s+\(\d+b\)\s*$', line)
            if not m:
                continue
            h, path = m.group(1), m.group(2)
            entries[path] = h
    return entries, exemptions


def walk_real_files(root, manifest_name, excludes):
    """Return the set of real relative file paths under root, excluding the manifest itself
    and anything matching an exclude glob (always excludes .git)."""
    real = set()
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d != '.git']
        for fn in filenames:
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, root)
            if rel == manifest_name:
                continue
            if any(fnmatch.fnmatch(rel, pat) for pat in excludes):
                continue
            real.add(rel)
    return real


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("manifest_path")
    ap.add_argument("--root", default=".", help="directory the manifest's paths are relative to")
    ap.add_argument("--exclude", action="append", default=[],
                     help="glob pattern to exclude from the stowaway check (repeatable)")
    args = ap.parse_args()

    manifest_name = os.path.basename(args.manifest_path)
    entries, declared_exemptions = parse_manifest(args.manifest_path)
    N = len(entries)

    ok = 0
    mismatched = []
    missing = []
    for path, expected_hash in entries.items():
        full = os.path.join(args.root, path)
        try:
            with open(full, "rb") as f:
                actual = hashlib.sha256(f.read()).hexdigest()
            if actual == expected_hash:
                ok += 1
            else:
                mismatched.append(path)
        except FileNotFoundError:
            missing.append(path)

    real_files = walk_real_files(args.root, manifest_name, args.exclude)
    listed_files = set(entries.keys())
    stowaways = sorted(real_files - listed_files - declared_exemptions)

    print(f"manifest: {ok}/{N} listed files verify")
    if declared_exemptions:
        print(f"exemptions: {len(declared_exemptions)} declared in the manifest itself ({', '.join(sorted(declared_exemptions))})")
    if mismatched:
        print(f"  MISMATCH ({len(mismatched)}):")
        for p in mismatched:
            print(f"    {p}")
    if missing:
        print(f"  MISSING ({len(missing)}):")
        for p in missing:
            print(f"    {p}")
    print(f"stowaways: {len(stowaways)} unlisted file(s) present on disk")
    if stowaways:
        for p in stowaways:
            print(f"    STOWAWAY: {p}")

    clean = (ok == N) and (N > 0) and (not mismatched) and (not missing) and (not stowaways)
    print("VERDICT: PASS" if clean else "VERDICT: FAIL")
    sys.exit(0 if clean else 1)


if __name__ == "__main__":
    main()
